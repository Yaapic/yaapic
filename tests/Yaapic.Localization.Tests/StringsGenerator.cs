using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Yaapic.Localization.Tests;

/// <summary>Turns the two catalogue files into the source of <c>Strings</c>; see <see cref="StringsGeneratorTests"/>.</summary>
internal static partial class StringsGenerator
{
    public static Dictionary<string, string> Read(string json)
    {
        using var doc = JsonDocument.Parse(json);
        return doc.RootElement.EnumerateObject().ToDictionary(p => p.Name, p => p.Value.GetString() ?? "");
    }

    /// <summary>The placeholder indexes of a text, for example {0} and {1}.</summary>
    public static int[] Placeholders(string text) =>
        [.. PlaceholderPattern().Matches(text).Select(m => int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture)).Distinct().Order()];

    public static string MemberName(string key) =>
        string.Concat(key.Split('.', '-', '_').Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

    public static string Generate(string englishJson, string frenchJson)
    {
        var english = Read(englishJson);
        var french = Read(frenchJson);
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> from strings.en.json and strings.fr.json; do not edit. </auto-generated>\n");
        sb.Append("#nullable enable\nusing System.Globalization;\n\nnamespace Yaapic.Localization;\n\n");
        sb.Append("/// <summary>Every user-visible text of the app, in the current language.</summary>\n");
        sb.Append("public static class Strings\n{\n");
        var names = new HashSet<string>();
        foreach (var key in english.Keys.Order(StringComparer.Ordinal))
        {
            var name = MemberName(key);
            if (!names.Add(name))
            {
                throw new InvalidOperationException($"Two keys give the member {name}.");
            }

            var en = english[key];
            french.TryGetValue(key, out var fr);
            var pick = $"Localizer.Pick({Literal(en)}, {(fr is null ? "null" : Literal(fr))})";
            var count = Placeholders(en) is { Length: > 0 } p ? p[^1] + 1 : 0;
            sb.Append($"    /// <summary>{Escape(en)}</summary>\n");
            if (count == 0)
            {
                sb.Append($"    public static string {name} => {pick};\n\n");
            }
            else
            {
                var args = string.Join(", ", Enumerable.Range(0, count).Select(i => $"object? a{i}"));
                var list = string.Join(", ", Enumerable.Range(0, count).Select(i => $"a{i}"));
                sb.Append($"    public static string {name}({args}) =>\n        string.Format(CultureInfo.CurrentCulture, {pick}, {list});\n\n");
            }
        }

        sb.Length -= 1;
        sb.Append("}\n");
        return sb.ToString();
    }

    private static string Escape(string text) =>
        text.Replace("&", "&amp;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);

    private static string Literal(string text) =>
        "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal).Replace("\n", "\\n", StringComparison.Ordinal) + "\"";

    [GeneratedRegex(@"\{(\d+)\}")]
    private static partial Regex PlaceholderPattern();
}
